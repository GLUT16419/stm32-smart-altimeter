/* MLP 前向：输入 5 → Dense(8,tanh) → Dense(1,linear) → 输出 1 */
static float bp_forward_mlp(const float x[5],
                           const float w0[40], const float b0[8],
                           const float w2[8],  const float b2[1])
{
    float h[8];
    for (int o = 0; o < 8; o++) {
        float acc = b0[o];
        for (int i = 0; i < 5; i++)
            acc += w0[o * 5 + i] * x[i];   /* X-CUBE-AI Dense: W[out*in + in_idx] */
        h[o] = tanhf(acc);
    }
    float y = b2[0];
    for (int o = 0; o < 8; o++)
        y += w2[o] * h[o];
    return y;
}

float BP_Denoise_Update(BP_Denoise_t *s,
                        const float w0[40], const float b0[8],
                        const float w2[8],  const float b2[1],
                        float raw_hpa, float scale, float ema_alpha)
{
    /* 左移滑窗，新值放到末尾 → 维护 [t-4, t-3, t-2, t-1, t] */
    for (int j = 0; j < 4; j++) s->hist[j] = s->hist[j + 1];
    s->hist[4] = raw_hpa;
    if (s->cnt < 5) { s->cnt++; return 0.0f; }   /* 滑窗未满，不推理 */

    /* 归一化: (x - center) / scale,  center = 第3个点 */
    float center = s->hist[2];
    float bi[5];
    for (int j = 0; j < 5; j++) bi[j] = (s->hist[j] - center) / scale;

    /* 推理 + 反归一化 → 去噪气压 (hPa) */
    float bo = bp_forward_mlp(bi, w0, b0, w2, b2);
    float denoised = bo * scale + center;

    /* EMA 后处理：消除 BP 输出高频抖动 */
    if (!s->inited) { s->ema = denoised; s->inited = 1; }
    else s->ema = ema_alpha * denoised + (1.0f - ema_alpha) * s->ema;
    return s->ema;
}
